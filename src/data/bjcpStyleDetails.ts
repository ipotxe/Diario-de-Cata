/**
 * Returns a deterministic "Style of the Day" based on the current date string (YYYY-MM-DD),
 * ensuring every day shows a fresh style consistently across all user sessions on that day.
 */
export function getStyleOfTheDay(forcedSeed?: string): StyleDetail {
  const dateStr = forcedSeed || new Date().toISOString().slice(0, 10);
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
    hash |= 0; // Convert to 32bit integer
  }
  const positiveIndex = Math.abs(hash) % BJCP_STYLE_DETAILS_DB.length;
  return BJCP_STYLE_DETAILS_DB[positiveIndex];
}

/**
 * Returns a totally random style from the database.
 */
export function getRandomStyle(excludeId?: string): StyleDetail {
  const available = excludeId
    ? BJCP_STYLE_DETAILS_DB.filter((s) => s.id !== excludeId)
    : BJCP_STYLE_DETAILS_DB;
  const randomIndex = Math.floor(Math.random() * available.length);
  return available[randomIndex];
}
